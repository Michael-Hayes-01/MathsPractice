/*
 * ==========================================
 * PASSAGES FOR PUNCTUATION PRACTICE
 * ==========================================
 *
 * Each addPassage(...) is one passage, written
 * with all of its punctuation. The page takes
 * out the marks being practised and the child
 * puts them back. Marks that aren't being
 * practised stay in.
 *
 * Use straight speech marks (") and keep to
 * one mark between words, plus speech marks:
 *
 *     "Only one," said Dad.
 *
 * A name at the start of a sentence should
 * also appear somewhere mid-sentence (in any
 * passage), otherwise it is shown with a
 * small letter until the full stop is added.
 */


